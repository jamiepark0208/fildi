const extraRows: DataSourceCatalogRow[] = [];

/** Rows the Settings catalog renders. Extra rows are tests and later registrations, not a panel edit. */
export function catalogRows(): DataSourceCatalogRow[] {
  const byId = new Map<string, DataSourceCatalogRow>();
  for (const row of [...DATA_SOURCES_CATALOG, ...RESEARCH_TOOLS]) byId.set(row.id, row);
  for (const row of extraRows) byId.set(row.id, row);
  return [...byId.values()];
}

/** Add a source. The returned function removes it. The panel is not edited. */
export function registerCatalogRow(row: DataSourceCatalogRow): () => void {
  extraRows.push(row);
  return () => {
    const i = extraRows.findIndex((r) => r.id === row.id);
    if (i >= 0) extraRows.splice(i, 1);
  };
}

/** Recorded usage, not a claim that all callers are metered or a vendor is healthy. */
export function catalogUsage(
  rows: DataSourceCatalogRow[],
  history: { source: string; date: string; callsMade: number }[],
  today: string,
) {
  const usage = new Map<string, { total: number; today: number | null; last: string | null }>();
  for (const record of history) {
    if (record.date > today || !Number.isFinite(record.callsMade) || record.callsMade < 0) continue;
    const key = record.source === "alpha_vantage" ? "av" : record.source;
    const value = usage.get(key) ?? { total: 0, today: null, last: null };
    value.total += record.callsMade;
    if (record.date === today) value.today = (value.today ?? 0) + record.callsMade;
    if (record.callsMade > 0 && (!value.last || record.date > value.last)) value.last = record.date;
    usage.set(key, value);
  }
  return rows.map((row) => {
    const measured = row.usageKey ? usage.get(row.usageKey) : undefined;
    const callsToday = measured?.today ?? null;
    const limit = row.dailyLimit;
    const pct = callsToday != null && limit != null && limit > 0
      ? Math.round(callsToday / limit * 1000) / 10 : null;
    return {
      ...row,
      callsToday,
      calls30d: measured?.total ?? null,
      lastCallDate: measured?.last ?? null,
      avgDailyCalls: measured ? Math.round(measured.total / 30 * 10) / 10 : null,
      pctOfDailyLimit: pct,
      nearLimit: pct != null && pct >= 70,
    };
  });
}
